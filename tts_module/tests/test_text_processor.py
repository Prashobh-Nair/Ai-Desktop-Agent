"""
Unit Tests for TextProcessor.
Validates normalization of markdown, numbers, currencies, dates, abbreviations, and sentence chunking.
"""

import unittest
from tts_module.src.text_processor import TextProcessor


class TestTextProcessor(unittest.TestCase):

    def setUp(self):
        self.processor = TextProcessor(max_chunk_chars=150, max_chunk_words=25)

    def test_markdown_stripping(self):
        sample = "**Autonomous Agent** is running in *production* mode with `#tag` and [Docs](https://docs.local)."
        cleaned = self.processor.clean_markdown(sample)
        self.assertNotIn("**", cleaned)
        self.assertNotIn("*", cleaned)
        self.assertNotIn("[Docs]", cleaned)
        self.assertIn("Autonomous Agent is running in production mode", cleaned)

    def test_code_block_stripping(self):
        sample = "Here is the result:\n```python\nprint('hello')\n```\nAll done."
        cleaned = self.processor.clean_markdown(sample)
        self.assertNotIn("```", cleaned)
        self.assertIn("Here is the code: print('hello')", cleaned)

    def test_cardinal_numbers(self):
        self.assertEqual(TextProcessor.int_to_words(0), "zero")
        self.assertEqual(TextProcessor.int_to_words(7), "seven")
        self.assertEqual(TextProcessor.int_to_words(42), "forty-two")
        self.assertEqual(TextProcessor.int_to_words(100), "one hundred")
        self.assertEqual(TextProcessor.int_to_words(1500), "one thousand five hundred")

    def test_number_normalization_in_text(self):
        normalized = self.processor.normalize("I found 42 files and 3 errors.")
        self.assertIn("forty-two", normalized)
        self.assertIn("three", normalized)

    def test_currency_normalization(self):
        normalized = self.processor.normalize("The total price is $15.50 and £10.")
        self.assertIn("fifteen dollars and fifty cents", normalized)
        self.assertIn("ten pounds", normalized)

    def test_percentage_normalization(self):
        normalized = self.processor.normalize("CPU utilization is at 85% and memory is 92.5%.")
        self.assertIn("eighty-five percent", normalized)
        self.assertIn("ninety-two point five percent", normalized)

    def test_units_normalization(self):
        normalized = self.processor.normalize("Your system has 8 GB of RAM and runs at 2.4 GHz.")
        self.assertIn("eight gigabytes of R A M", normalized)
        self.assertIn("two point four gigahertz", normalized)

    def test_acronym_normalization(self):
        normalized = self.processor.normalize("The AI agent uses STT and TTS connected to an LLM.")
        self.assertIn("A I", normalized)
        self.assertIn("S T T", normalized)
        self.assertIn("T T S", normalized)
        self.assertIn("L L M", normalized)

    def test_time_normalization(self):
        normalized = self.processor.normalize("The reminder is set for 10:30 AM.")
        self.assertIn("ten thirty A M", normalized)

    def test_sentence_splitting(self):
        text = "Hello there! How are you doing today? I am your desktop assistant. Let us get started."
        sentences = self.processor.split_into_sentences(text)
        self.assertEqual(len(sentences), 4)
        self.assertEqual(sentences[0], "Hello there!")
        self.assertEqual(sentences[1], "How are you doing today?")

    def test_long_text_chunking(self):
        long_text = (
            "We are developing an AI-Powered Autonomous Desktop Agent. "
            "The system is divided into three key modules: Speech-to-Text, Large Language Model brain, and Text-to-Speech. "
            "The Text-to-Speech engine uses Kokoro-82M, which delivers natural human-like speech offline. "
            "Even long responses generated by the language model are split into natural clauses and sentences."
        )
        chunks = self.processor.chunk_text(long_text)
        self.assertGreater(len(chunks), 1)
        for chunk in chunks:
            self.assertLessEqual(len(chunk), 200)

    def test_empty_and_whitespace_input(self):
        self.assertEqual(self.processor.normalize(""), "")
        self.assertEqual(self.processor.normalize("   "), "")
        self.assertEqual(self.processor.chunk_text(""), [])
        self.assertEqual(self.processor.chunk_text("   "), [])


if __name__ == "__main__":
    unittest.main()

